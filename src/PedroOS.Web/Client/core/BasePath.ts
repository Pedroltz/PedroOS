/**
 * Deployment base path helpers.
 *
 * When served by ASP.NET Core at the site root, `BASE` is empty and nothing changes.
 * The static export (GitHub Pages) injects `<meta name="pedroos-base" content="/PedroOS">`
 * and `<meta name="pedroos-static" content="true">`, so every root-relative URL and
 * route must be prefixed on the client as well.
 */
function readMeta(name: string): string {
  if (typeof document === 'undefined') {
    return '';
  }
  return document.querySelector<HTMLMetaElement>(`meta[name="${name}"]`)?.content ?? '';
}

export const BASE: string = readMeta('pedroos-base').replace(/\/+$/, '');
export const IS_STATIC: boolean = readMeta('pedroos-static') === 'true';

/** Prefixes a root-relative URL ("/assets/x.png") with the deployment base path. */
export function withBase(path: string): string {
  return path.startsWith('/') && !path.startsWith('//') ? `${BASE}${path}` : path;
}

/** Converts a browser pathname to an app route ("/PedroOS/projects/" -> "/projects"). */
export function stripBase(pathname: string): string {
  let p = pathname;
  if (BASE && (p === BASE || p.startsWith(`${BASE}/`))) {
    p = p.slice(BASE.length) || '/';
  }
  return p.length > 1 ? p.replace(/\/+$/, '') : p;
}

/** URL of the server-rendered fragment (or its pre-rendered static file). */
export function fragmentUrl(appId: string, args: Record<string, string>): string {
  const id = encodeURIComponent(appId);
  if (IS_STATIC) {
    const slug = args.slug ? `/${encodeURIComponent(args.slug)}` : '';
    return `${BASE}/fragments/${id}${slug}.html`;
  }
  const query = new URLSearchParams(args).toString();
  return `/fragments/${id}${query ? `?${query}` : ''}`;
}

/** Resume PDF is generated by the server at runtime, or pre-built as a static file. */
export function resumePdfUrl(): string {
  return IS_STATIC ? `${BASE}/resume/Pedro-Tunin-Resume.pdf` : '/resume/pdf';
}
